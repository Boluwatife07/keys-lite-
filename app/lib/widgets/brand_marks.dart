      );

  @override
  Widget build(BuildContext context) => CustomPaint(size: Size(height * viewBox.width / viewBox.height, height), painter: _MarkPainter(paths, viewBox, tint));
}

class _MarkPainter extends CustomPainter {
  _MarkPainter(this.paths, this.viewBox, this.tint);
  final List<(String, Color)> paths;
  final Size viewBox;
  final Color? tint;
  static final _cache = <String, Path>{};

  static Path _parse(String d) => _cache.putIfAbsent(d, () {
        final p = Path();
        writeSvgPathDataToPath(d, _Proxy(p));
        return p;
      });

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / viewBox.width, size.height / viewBox.height);
    for (final (d, c) in paths) {
      canvas.drawPath(_parse(d), Paint()..color = tint ?? c..isAntiAlias = true);
    }
  }

  @override
  bool shouldRepaint(_MarkPainter old) => old.tint != tint || old.paths != paths;
}

class _Proxy extends PathProxy {
  _Proxy(this.p);
  final Path p;
  @override
  void close() => p.close();
  @override
  void cubicTo(double x1, double y1, double x2, double y2, double x3, double y3) => p.cubicTo(x1, y1, x2, y2, x3, y3);
  @override
  void lineTo(double x, double y) => p.lineTo(x, y);
  @override
  void moveTo(double x, double y) => p.moveTo(x, y);
}

